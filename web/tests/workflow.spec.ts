import {test,expect} from '@playwright/test'
test('operator investigates evidence, reviews and follows up',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByLabel('Nama pengguna').fill(process.env.OPERATOR_USERNAME||'operator')
 await page.getByLabel('Kata sandi',{exact:true}).fill(process.env.OPERATOR_PASSWORD!)
 await page.getByRole('button',{name:'Masuk',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Ruang investigasi.'})).toBeVisible()
 await expect(page.getByText('SIMULASI MODEL',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Jalankan deteksi',exact:true}).click()
 await page.locator('.case-item').filter({hasText:'OT-001'}).click()
 if(await page.getByRole('button',{name:'Mulai investigasi',exact:true}).isVisible())await page.getByRole('button',{name:'Mulai investigasi',exact:true}).click()
 await expect(page.getByRole('button',{name:'Buka laporan bukti'})).toBeVisible({timeout:30000})
 await expect(page.locator('.case-numbers')).toContainText('38%')
 await page.getByRole('button',{name:'Buka laporan bukti'}).click()
 await expect(page.getByRole('heading',{name:'Observasi dari catatan sumber'})).toBeVisible()
 const staffing=page.locator('.evidence-card').filter({hasText:'Ketersediaan operator'})
 await expect(staffing).toContainText('31')
 await expect(staffing).toContainText('38')
 await expect(staffing).toContainText('3')
 await expect(staffing).toContainText('4')
 await staffing.click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.getByRole('dialog')).toContainText('SHA-256 snapshot')
 await page.getByRole('button',{name:'Tutup bukti'}).click()
 await expect(page.locator('.evidence-card').filter({hasText:'Interupsi mesin'})).toContainText('110 menit')
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:'test-results/report-desktop.png',fullPage:true})
 await page.getByRole('button',{name:'Tinjau rekomendasi'}).click()
 const first=page.locator('.recommendation').first()
 if(await first.getByRole('button',{name:'Setujui rekomendasi'}).isVisible()){
  await first.getByLabel('Catatan peninjau').fill('Ditinjau melalui uji browser sintetis.')
  await first.getByRole('button',{name:'Setujui rekomendasi'}).click()
  await expect(first.getByText('Disetujui',{exact:true})).toBeVisible()
 }
 const second=page.locator('.recommendation').nth(1)
 if(await second.getByRole('button',{name:'Tolak',exact:true}).isVisible()){
  await expect(second.getByRole('button',{name:'Tolak',exact:true})).toBeDisabled()
  await second.getByLabel('Catatan peninjau').fill('Butuh log tambahan.')
  await second.getByRole('button',{name:'Tolak',exact:true}).click()
  await expect(second.getByText('Ditolak',{exact:true})).toBeVisible()
 }
 await expect(page.locator('.audit-list')).toContainText('Keputusan review dicatat')
 await page.getByLabel('Instruksi investigasi lanjutan').fill('Periksa kembali bukti downtime tanpa menyimpulkan kausalitas.')
 await page.getByRole('button',{name:'Investigasi lanjutan',exact:true}).click()
 await expect(page.getByRole('button',{name:'Buka laporan bukti'})).toBeVisible({timeout:30000})
 await page.getByRole('tab',{name:'02 Laporan bukti'}).click()
 await page.setViewportSize({width:390,height:844})
 await expect(page.getByRole('heading',{name:'Observasi dari catatan sumber'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
 await page.screenshot({path:'test-results/report-mobile.png',fullPage:true})
 await page.getByRole('button',{name:'Keluar',exact:true}).click()
 await expect(page.getByRole('button',{name:'Masuk',exact:true})).toBeVisible()
 expect(errors).toEqual([])
})
